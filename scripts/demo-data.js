const PALETTE = ['#44cf6e', '#e9973f', '#a882ff', '#53dfdd', '#fb464c', '#e0de71'];

function seedDemo(store) {
  store.ensureDirs();
  const state = normalizeState({}, {});
  const graph = state.graphs[0];
  const notes = {};
  const byTitle = {};
  const now = Date.now();
  DEMO.forEach(([title, content], i) => {
    const id = 'n' + (now + i) + String(i).padStart(2, '0');
    notes[id] = {
      id, title, content, color: PALETTE[i % PALETTE.length],
      created: now + i, updated: now + i, graph: graph.id, links: [],
    };
    byTitle[title] = notes[id];
  });
  const link = (a, b, style = {}) => {
    if (!byTitle[a] || !byTitle[b]) return;
    byTitle[a].links.push({ id: byTitle[b].id, shape: style.shape || 'curve', arrow: style.arrow || 'solid' });
  };
  link('知识体系', '原子化笔记');
  link('知识体系', '费曼学习法', { arrow: 'hollow' });
  link('知识体系', '卡片盒笔记法', { shape: 'line' });
  link('知识体系', '间隔重复');
  link('原子化笔记', '双向链接');
  link('卡片盒笔记法', '原子化笔记', { arrow: 'none' });
  link('知识图谱', '双向链接');
  link('知识图谱', '力导向布局');
  link('力导向布局', '知识图谱', { arrow: 'hollow' });
  link('我的工作流', '知识体系');
  link('我的工作流', '卡片盒笔记法');
  link('孤岛笔记', '知识体系', { arrow: 'none' });

  graph.name = '知识体系图';
  state.graph_id = graph.id;
  state.selected = byTitle['知识体系'].id;
  graph.selected = state.selected;
  state.mode = 'view';
  store.saveAll(state, notes);
}

module.exports = { seedDemo };
